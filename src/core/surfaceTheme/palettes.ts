const BUILTIN_IDS = new Set<string>(SURFACE_THEMES.map((t) => t.id));

export function isBuiltinSurfaceThemeId(value: unknown): value is BuiltinSurfaceThemeId {
  return typeof value === 'string' && BUILTIN_IDS.has(value);
}

/**
 * Normalize a stored theme id (`null` or unknown becomes `'official'`).
 */
export function normalizeSurfaceThemeId(stored: unknown): SurfaceThemeId {
  if (stored === 'official' || stored === null || stored === undefined || stored === '') {
    return 'official';
  }
  if (isBuiltinSurfaceThemeId(stored)) {
    return stored;
  }
  return 'official';
}

export function getSurfaceTheme(id: SurfaceThemeId | string | null | undefined): SurfaceThemeDefinition | null {
  if (!id || id === 'official') return null;
  return SURFACE_THEMES.find((theme) => theme.id === id) ?? null;
}

export function listSurfaceThemeSummaries(): SurfaceThemeSummary[] {
  return SURFACE_THEMES.map(({ id, name, family, mode, description, accent, bg, mantle, surface, text }) => ({
    id,
    name,
    family,
    mode,
    description,
    accent,
    bg,
    mantle,
    surface,
    text,
  }));
}
